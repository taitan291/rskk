/// Convert hiragana in the standard block to katakana without changing other text.
pub fn to_katakana(input: &str) -> String {
    input
        .chars()
        .map(|ch| match ch {
            '\u{3041}'..='\u{3096}' => char::from_u32(ch as u32 + 0x60).unwrap_or(ch),
            '\u{309D}'..='\u{309F}' => char::from_u32(ch as u32 + 0x60).unwrap_or(ch),
            _ => ch,
        })
        .collect()
}

/// Convert full-width ASCII and ideographic space to ordinary ASCII.
pub fn to_zenkaku(input: &str) -> String {
    input
        .chars()
        .map(|ch| match ch {
            ' ' => '\u{3000}',
            '!'..='~' => char::from_u32(ch as u32 + 0xfee0).unwrap_or(ch),
            _ => ch,
        })
        .collect()
}

